import React, { useEffect, useRef, useState } from "react";
import { Copy, RefreshCw, Send, ShieldCheck, Sparkles } from "lucide-react";
import { FinSightAPI, FinancialPulse } from "../../services/finsightApi";
import { toast } from "sonner";

interface Props {
  pulse: FinancialPulse;
}

interface Message {
  from: "user" | "ai";
  text: string;
  toolAudit?: Array<{ toolName: string }>;
}

const starterMessage: Message = {
  from: "ai",
  text: "Ask a question about your finances. Responses are generated by the AI provider configured on the backend and can use your saved financial data.",
};

const suggestedQuestions = [
  "Summarize my spending this month",
  "Which categories have the highest expenses?",
  "Show my budget status",
  "What recurring payments do I have?",
];

export const AssistantView: React.FC<Props> = ({ pulse }) => {
  const [messages, setMessages] = useState<Message[]>([starterMessage]);
  const [conversationId, setConversationId] = useState<string>();
  const [input, setInput] = useState("");
  const [loading, setLoading] = useState(false);
  const messagesEndRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    messagesEndRef.current?.scrollIntoView({ behavior: "smooth" });
  }, [messages, loading]);

  const sendMessage = async (suggestion?: string) => {
    const text = (suggestion ?? input).trim();
    if (!text || loading) return;

    setInput("");
    setMessages((previous) => [...previous, { from: "user", text }]);
    setLoading(true);

    try {
      const response = await FinSightAPI.askAssistant(text, conversationId);
      setConversationId(response.conversationId);
      setMessages((previous) => [
        ...previous,
        { from: "ai", text: response.text, toolAudit: response.toolAudit },
      ]);
    } catch (error) {
      const message = error instanceof Error ? error.message : "The assistant request failed.";
      toast.error(message);
      setMessages((previous) => [...previous, { from: "ai", text: `Request failed: ${message}` }]);
    } finally {
      setLoading(false);
    }
  };

  const copyMessage = async (text: string) => {
    try {
      await navigator.clipboard.writeText(text);
      toast.success("Response copied.");
    } catch {
      toast.error("Could not copy the response.");
    }
  };

  return (
    <section className="space-y-6">
      <div>
        <p className="text-[10px] font-bold tracking-wider text-slate-400 uppercase">YOUR MONEY, EXPLAINED</p>
        <h1 className="text-2xl font-bold font-heading text-slate-900 dark:text-white">AI Financial Assistant</h1>
        <p className="text-xs text-slate-500 dark:text-slate-400">
          The assistant runs through the backend using the AI provider configured by the server.
        </p>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
        <div className="lg:col-span-2 bg-white dark:bg-[#121f1c] rounded-2xl border border-slate-200 dark:border-[#21352f] flex flex-col h-[650px] overflow-hidden shadow-xs">
          <div className="p-4 border-b border-slate-100 dark:border-[#21352f] flex items-center justify-between">
            <div className="flex items-center gap-3">
              <span className="w-8 h-8 rounded-full bg-emerald-100 dark:bg-emerald-950/60 text-[#16a57a] flex items-center justify-center">
                <Sparkles size={16} />
              </span>
              <div>
                <h2 className="font-semibold text-xs text-slate-900 dark:text-white">FinSight AI</h2>
                <p className="text-[10px] text-slate-400">Server-configured provider · private account context</p>
              </div>
            </div>
            <button
              onClick={() => { setMessages([starterMessage]); setConversationId(undefined); }}
              className="p-1.5 rounded-lg text-slate-400 hover:bg-slate-100 dark:hover:bg-[#1a2f29]"
              title="Start a new conversation"
              aria-label="Start a new conversation"
            >
              <RefreshCw size={15} />
            </button>
          </div>

          <div className="flex-1 p-4 overflow-y-auto space-y-4">
            {messages.map((message, index) => (
              <div key={`${index}-${message.from}`} className={`flex gap-3 max-w-[90%] ${message.from === "user" ? "ml-auto flex-row-reverse" : ""}`}>
                <span className={`w-7 h-7 rounded-full flex-shrink-0 flex items-center justify-center text-xs font-bold ${message.from === "user" ? "bg-slate-900 text-white dark:bg-slate-700" : "bg-[#e6f7f0] dark:bg-[#18352c] text-[#16a57a]"}`}>
                  {message.from === "user" ? "You" : <Sparkles size={13} />}
                </span>
                <div className={`p-3.5 rounded-2xl text-xs leading-relaxed group whitespace-pre-wrap break-words ${message.from === "user" ? "bg-[#e6f7f0] text-slate-900 rounded-tr-none font-medium" : "bg-[#f8faf9] dark:bg-[#0e1715] text-slate-800 dark:text-slate-200 rounded-tl-none border border-slate-100 dark:border-[#21352f]"}`}>
                  <div className="flex items-start justify-between gap-3">
                    <p className="flex-1">{message.text}</p>
                    {message.from === "ai" && index > 0 && (
                      <button onClick={() => void copyMessage(message.text)} aria-label="Copy response" className="text-slate-400 hover:text-slate-700 dark:hover:text-white">
                        <Copy size={12} />
                      </button>
                    )}
                  </div>
                  {message.toolAudit && message.toolAudit.length > 0 && (
                    <div className="mt-2 flex flex-wrap gap-1">
                      {message.toolAudit.map((tool, toolIndex) => (
                        <span key={`${tool.toolName}-${toolIndex}`} className="rounded bg-slate-200/70 px-2 py-0.5 text-[9px] font-mono text-slate-700 dark:bg-[#1a3830] dark:text-emerald-300">
                          {tool.toolName}
                        </span>
                      ))}
                    </div>
                  )}
                </div>
              </div>
            ))}
            {loading && (
              <div className="flex items-center gap-2 text-xs text-slate-400 italic">
                <Sparkles size={14} className="animate-spin text-[#16a57a]" />
                <span>Waiting for the backend AI service…</span>
              </div>
            )}
            <div ref={messagesEndRef} />
          </div>

          <div className="px-4 py-2 border-t border-slate-100 dark:border-[#1e342c] flex gap-1.5 overflow-x-auto">
            {suggestedQuestions.map((question) => (
              <button key={question} onClick={() => void sendMessage(question)} disabled={loading} className="px-2.5 py-1 rounded-full text-[11px] whitespace-nowrap bg-white hover:bg-slate-100 dark:bg-[#162722] dark:hover:bg-[#1c362e] border border-slate-200 dark:border-[#21352f] text-slate-700 dark:text-emerald-300 disabled:opacity-50">
                {question}
              </button>
            ))}
          </div>

          <div className="p-3 border-t border-slate-100 dark:border-[#21352f] flex items-center gap-2">
            <input
              value={input}
              onChange={(event) => setInput(event.target.value)}
              onKeyDown={(event) => { if (event.key === "Enter") void sendMessage(); }}
              placeholder="Ask a question about your financial data…"
              className="flex-1 px-3 py-2 text-xs bg-slate-50 dark:bg-[#0c1412] rounded-xl border border-slate-200 dark:border-[#21352f] outline-none text-slate-900 dark:text-white focus:border-[#16a57a]"
            />
            <button onClick={() => void sendMessage()} disabled={loading || !input.trim()} className="w-9 h-9 rounded-xl bg-[#16a57a] hover:bg-[#138e69] disabled:opacity-40 text-white flex items-center justify-center" title="Send message">
              <Send size={15} />
            </button>
          </div>
        </div>

        <aside className="bg-[#f0f7f4] dark:bg-[#0e1715] rounded-2xl p-6 border border-[#dcefe6] dark:border-[#21352f] space-y-5 h-fit">
          <div className="flex items-center gap-1.5 text-xs font-bold text-[#16a57a] tracking-wider uppercase">
            <ShieldCheck size={14} /> Ledger context
          </div>
          <h2 className="font-heading font-semibold text-slate-900 dark:text-white text-base">Current month</h2>
          <div className="space-y-3 divide-y divide-slate-200/60 dark:divide-[#21352f] text-xs">
            <div className="pt-2 flex justify-between"><span className="text-slate-500">Income</span><strong>₹{pulse.totalIncome.toLocaleString("en-IN")}</strong></div>
            <div className="pt-2 flex justify-between"><span className="text-slate-500">Expenses</span><strong>₹{pulse.totalExpenses.toLocaleString("en-IN")}</strong></div>
            <div className="pt-2 flex justify-between"><span className="text-slate-500">Net cash flow</span><strong className="text-emerald-600">₹{pulse.currentSavings.toLocaleString("en-IN")}</strong></div>
            <div className="pt-2 flex justify-between"><span className="text-slate-500">Savings rate</span><strong className="text-emerald-600">{pulse.savingsRate.toFixed(1)}%</strong></div>
            <div className="pt-2 flex justify-between"><span className="text-slate-500">Budget remaining</span><strong>₹{pulse.budgetRemaining.toLocaleString("en-IN")}</strong></div>
          </div>
          <p className="text-[11px] text-slate-500 dark:text-slate-400 leading-relaxed">
            Values are based on data currently recorded in your account. AI requests are sent to the configured backend provider, not to a browser-stored API key.
          </p>
        </aside>
      </div>
    </section>
  );
};
