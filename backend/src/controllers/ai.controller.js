import { aiAssistantService } from '../integrations/ai/aiAssistant.service.js';
import { ApiResponse } from '../utils/ApiResponse.js';
import { asyncHandler } from '../utils/asyncHandler.js';
import { env } from '../config/env.js';

export const aiController = {
  chat: asyncHandler(async (req, res) => {
    const userId = req.user?.id || 'demo-user-1';

    // 1. Try dedicated Python FastAPI AI microservice
    try {
      const pyRes = await fetch(`${env.AI_SERVICE_URL}/api/v1/copilot/chat`, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'x-service-api-key': env.AI_SERVICE_API_KEY,
          'x-user-id': userId,
        },
        body: JSON.stringify({
          message: req.body.message,
          conversation_id: req.body.conversationId,
        }),
      });

      if (pyRes.ok) {
        const pyData = await pyRes.json();
        const aiData = pyData.data || {};
        return res.status(200).json(
          ApiResponse.success('Response generated by AI Copilot', {
            message: aiData.answer || aiData.message,
            intent: aiData.intent,
            keyFigures: aiData.key_figures,
            recommendations: aiData.recommendations,
            warnings: aiData.warnings,
            suggestedFollowUps: aiData.suggested_follow_ups,
            dataSources: aiData.data_sources,
            conversationId: req.body.conversationId || 'conv-default',
          })
        );
      }
    } catch {
      // Python microservice initializing, fallback to internal engine
    }

    // 2. Resilient fallback
    const result = await aiAssistantService.chat(userId, req.body);
    res.status(200).json(ApiResponse.success('Response generated', result));
  }),

  getSummary: asyncHandler(async (req, res) => {
    const userId = req.user?.id || 'demo-user-1';
    try {
      const pyRes = await fetch(`${env.AI_SERVICE_URL}/api/v1/copilot/financial-summary`, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'x-service-api-key': env.AI_SERVICE_API_KEY,
          'x-user-id': userId,
        },
      });
      if (pyRes.ok) {
        const pyData = await pyRes.json();
        return res.status(200).json(pyData);
      }
    } catch {}
    res.status(200).json(ApiResponse.success('Summary fallback', {}));
  }),

  categorize: asyncHandler(async (req, res) => {
    const userId = req.user?.id || 'demo-user-1';
    try {
      const pyRes = await fetch(`${env.AI_SERVICE_URL}/api/v1/expenses/categorize`, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'x-service-api-key': env.AI_SERVICE_API_KEY,
          'x-user-id': userId,
        },
        body: JSON.stringify(req.body),
      });
      if (pyRes.ok) {
        const pyData = await pyRes.json();
        return res.status(200).json(pyData);
      }
    } catch {}
    res.status(200).json(ApiResponse.success('Categorized fallback', { category: 'Other', confidence: 0.5 }));
  }),

  forecast: asyncHandler(async (req, res) => {
    const userId = req.user?.id || 'demo-user-1';
    try {
      const pyRes = await fetch(`${env.AI_SERVICE_URL}/api/v1/forecast/month-end`, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'x-service-api-key': env.AI_SERVICE_API_KEY,
          'x-user-id': userId,
        },
      });
      if (pyRes.ok) {
        const pyData = await pyRes.json();
        return res.status(200).json(pyData);
      }
    } catch {}
    res.status(200).json(ApiResponse.success('Forecast fallback', {}));
  }),

  affordability: asyncHandler(async (req, res) => {
    const userId = req.user?.id || 'demo-user-1';
    try {
      const pyRes = await fetch(`${env.AI_SERVICE_URL}/api/v1/shopping/affordability`, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'x-service-api-key': env.AI_SERVICE_API_KEY,
          'x-user-id': userId,
        },
        body: JSON.stringify(req.body),
      });
      if (pyRes.ok) {
        const pyData = await pyRes.json();
        return res.status(200).json(pyData);
      }
    } catch {}
    res.status(200).json(ApiResponse.success('Affordability fallback', {}));
  }),

  getConversations: asyncHandler(async (req, res) => {
    const userId = req.user?.id || 'demo-user-1';
    const conversations = await aiAssistantService.getConversations(userId);
    res.status(200).json(ApiResponse.success('Conversations retrieved', { conversations }));
  }),

  getConversation: asyncHandler(async (req, res) => {
    const userId = req.user?.id || 'demo-user-1';
    const conversation = await aiAssistantService.getConversation(userId, req.params.id);
    res.status(200).json(ApiResponse.success('Conversation retrieved', { conversation }));
  }),

  deleteConversation: asyncHandler(async (req, res) => {
    const userId = req.user?.id || 'demo-user-1';
    const result = await aiAssistantService.deleteConversation(userId, req.params.id);
    res.status(200).json(ApiResponse.success(result.message));
  }),
};
